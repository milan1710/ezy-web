/**
 * Small wrapper so content data can reference icons by a readable string
 * instead of importing components into data files.
 */
export default function Icon({ name, size = 18, strokeWidth = 1.8, className, ...rest }) {
  const Component = iconMap[name] || Info
  return <Component size={size} strokeWidth={strokeWidth} className={className} aria-hidden="true" {...rest} />
}
